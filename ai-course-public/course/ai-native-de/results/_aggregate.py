"""
Aggregate 100x review scores from all 19 modules of the AI-Native DE course.

Reads:
  - M1-M3: course/ai-native-de/results/100x_review_*.json (old format)
  - M4-M19: <module>/results/N<NN>.L<NN>.review.json (new format)

Writes:
  - course/ai-native-de/results/_all_modules_review.md  (one-row-per-module table)
  - prints to stdout
"""
from __future__ import annotations

import json
import os
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent  # course/ai-native-de
LESSONS = ROOT / "lessons"

MODULES = [
    ("M01", "L1", "m01-foundations"),
    ("M02", "L2", "m02-vector-math"),
    ("M03", "L3", "m03-embeddings"),
    ("M04", "L4", "m04-ann"),
    ("M05", "L5", "m05-ingestion"),
    ("M06", "L6", "m06-chunking"),
    ("M07", "L7", "m07-retrieval"),
    ("M08", "L8", "m08-llm-fundamentals"),
    ("M09", "L9", "m09-rag-e2e"),
    ("M10", "L10", "m10-evaluation"),
    ("M11", "L11", "m11-observability"),
    ("M12", "L12", "m12-security"),
    ("M13", "L13", "m13-agents-mcp"),
    ("M14", "L14", "m14-data-platforms"),
    ("M15", "L15", "m15-staff-design"),
    ("M16", "L16", "m16-fullstack"),
    ("M17", "L17", "m17-product-metrics"),
    ("M18", "L18", "m18-leadership"),
    ("M19", "L19", "m19-capstone"),
]


def latest_score_for_module(module_dir: str, m_id: str) -> tuple[int, int, str] | None:
    """Return (last_total, best_total, source_path) for a module, or None."""
    mod_path = LESSONS / module_dir
    # Try the per-module results dir first (M4-M19)
    results_dir = mod_path / "results"
    candidates: list[Path] = []
    if results_dir.exists():
        # Match any *.review.json in the dir; different lessons use different naming
        # (e.g. M4.L4, M19.CAPSTONE)
        candidates.extend(sorted(results_dir.glob("*.review.json"), reverse=True))
    # Then course-wide results dir (M1-M3 use a different filename pattern)
    course_results = ROOT / "results"
    if course_results.exists() and not candidates:
        for c in sorted(course_results.glob("100x_review_*.json"), reverse=True):
            try:
                data = json.loads(c.read_text())
            except Exception:
                continue
            lesson = data.get("lesson", "")
            if module_dir in lesson:
                candidates.append(c)
                break
    for c in candidates:
        try:
            data = json.loads(c.read_text())
        except Exception:
            continue
        # New format (M4-M19): total_mean, total_std
        if "total_mean" in data:
            return (
                int(round(data.get("total_mean", 0))),
                int(round(data.get("total_mean", 0))),
                str(c),
            )
        # Old format (M1-M3): last_total, best_total
        if "last_total" in data:
            return (
                int(data.get("last_total", 0)),
                int(data.get("best_total", 0)),
                str(c),
            )
        # M1-M3 history-based
        history = data.get("history") or []
        if history:
            last = int(history[-1].get("total", 0))
            best = max(int(h.get("total", 0)) for h in history)
            return (last, best, str(c))
    return None


def main() -> None:
    print("=" * 78)
    print("  AI-Native DE Course -- 100x review summary (all 19 modules)")
    print("=" * 78)
    rows: list[tuple[str, str, str, int, int, str]] = []
    for m_id, l_id, mdir in MODULES:
        sc = latest_score_for_module(mdir, m_id)
        if sc is None:
            rows.append((m_id, l_id, mdir, 0, 0, "NO REVIEW"))
            continue
        last, best, src = sc
        rows.append((m_id, l_id, mdir, last, best, src))
    # print table
    print(f"{'Module':<7} {'Dir':<24} {'Last':>6} {'Best':>6}  Source")
    print("-" * 78)
    for m, l, d, last, best, src in rows:
        print(f"{m:<7} {d:<24} {last:>6} {best:>6}  {Path(src).name}")
    # write markdown
    out = ROOT / "results" / "_all_modules_review.md"
    lines: list[str] = []
    lines.append("# AI-Native DE Course -- 100x Review (all 19 modules)\n")
    lines.append("| Module | Directory | Last / 100 | Best / 100 |")
    lines.append("|---|---|---:|---:|")
    for m, l, d, last, best, _ in rows:
        lines.append(f"| {m} | {d} | {last} | {best} |")
    total_last = sum(r[3] for r in rows)
    total_best = sum(r[4] for r in rows)
    n = len(rows)
    lines.append(f"\n**Mean last:** {total_last / n:.1f} / 100")
    lines.append(f"**Mean best:** {total_best / n:.1f} / 100")
    lines.append(f"\n*Generated by `_aggregate.py` -- reads each module's latest `_review_100x.py` output.*\n")
    out.write_text("\n".join(lines))
    print(f"\nWrote: {out}")


if __name__ == "__main__":
    main()