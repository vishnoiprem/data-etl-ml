"""HTTP-level tests for the agentic coding service."""

from __future__ import annotations

import os
import sys
import tempfile
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.normpath(os.path.join(HERE, "..", "..")))

from common.storage import KeyValueStore  # noqa: E402
from code.app import create_app  # noqa: E402
from code.service import AgentService  # noqa: E402


class AgentAppTests(unittest.TestCase):
    def setUp(self) -> None:
        self.tmpdir = tempfile.mkdtemp()
        store = KeyValueStore(
            "test_agent_app",
            persist_path=os.path.join(self.tmpdir, "agent.json"),
        )
        self.svc = AgentService(
            store=store,
            workspace_root=self.tmpdir,
            default_workspace="ws",
        )
        self.app = create_app(self.svc)
        self.client = self.app.test_client()

    def test_health(self):
        r = self.client.get("/health")
        self.assertEqual(r.status_code, 200)
        self.assertTrue(r.get_json()["ok"])

    def test_create_session(self):
        r = self.client.post("/api/sessions", json={"user_id": "u1"})
        self.assertEqual(r.status_code, 201)
        body = r.get_json()
        self.assertEqual(body["user_id"], "u1")
        self.assertIn("workspace", body)

    def test_get_session(self):
        r1 = self.client.post("/api/sessions", json={"user_id": "u1"})
        sid = r1.get_json()["session_id"]
        r2 = self.client.get(f"/api/sessions/{sid}")
        self.assertEqual(r2.status_code, 200)
        self.assertEqual(r2.get_json()["session_id"], sid)

    def test_run_turn(self):
        r1 = self.client.post("/api/sessions", json={"user_id": "u1"})
        sid = r1.get_json()["session_id"]
        r2 = self.client.post(
            f"/api/sessions/{sid}/messages",
            json={"content": "list the files"},
        )
        self.assertEqual(r2.status_code, 200)
        body = r2.get_json()
        self.assertGreater(len(body["new_turns"]), 0)
        first = body["new_turns"][0]
        self.assertEqual(first["role"], "assistant")
        self.assertIsNotNone(first["tool_call"])

    def test_create_file_via_turn(self):
        r1 = self.client.post("/api/sessions", json={"user_id": "u1"})
        sid = r1.get_json()["session_id"]
        self.client.post(
            f"/api/sessions/{sid}/messages",
            json={"content": "create hello.txt"},
        )
        r3 = self.client.get(f"/api/sessions/{sid}/files")
        self.assertEqual(r3.status_code, 200)
        paths = [f["path"] for f in r3.get_json()]
        self.assertIn("hello.txt", paths)
        r4 = self.client.get(f"/api/sessions/{sid}/files/hello.txt")
        self.assertEqual(r4.status_code, 200)
        self.assertIn("Generated by the agent", r4.get_data(as_text=True))

    def test_read_file_rejects_traversal(self):
        r1 = self.client.post("/api/sessions", json={"user_id": "u1"})
        sid = r1.get_json()["session_id"]
        r2 = self.client.get(f"/api/sessions/{sid}/files/../etc/passwd")
        self.assertEqual(r2.status_code, 404)

    def test_metrics_endpoint(self):
        r = self.client.get("/metrics")
        self.assertEqual(r.status_code, 200)
        self.assertIn("sessions_created_total", r.get_data(as_text=True))


if __name__ == "__main__":
    unittest.main()
